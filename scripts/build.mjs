import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ['packages/fusion/client/entry.tsx'],
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: ['chrome132'],
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  loader: { '.css': 'text' },
  write: false,
  sourcemap: false,
  minify: false,
  logLevel: 'warning',
});
const output = path.join(root, 'packages/fusion/lib/client.js');
await mkdir(path.dirname(output), { recursive: true });
const bundle = `// DSH ModuleLoader client bundle; generated by scripts/build.mjs\nwindow.__ModuleLoader__.load({\n  id: '@dsh-forge/fusion',\n  factory(require) {\n    const module = { exports: {} };\n    const exports = module.exports;\n${result.outputFiles[0].text}\n    return module.exports;\n  },\n});\n`;
await writeFile(output, bundle);
console.log(`Built Fusion client (${Buffer.byteLength(bundle)} bytes).`);
